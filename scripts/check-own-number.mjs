import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { normalizeE164, providerHasVerifiedNumber, requireOwnerVerifiedCaller, createTelnyxVerifiedNumbers } from "../caller-identity.js";
const read = path => readFileSync(new URL("../" + path, import.meta.url), "utf8");
const verified = number => ({ data: { record_type: "verified_number", phone_number: number, verified_at: "2026-09-29T12:00:00Z" } });
const n1 = "+4512345678", n2 = "+4598765432";
assert.equal(normalizeE164(" +45 12 34 56 78 "), n1);
for (const bad of ["", "+45", "12345678", "+45123ABCD", {}, "+000123456789", "a".repeat(41)]) assert.equal(normalizeE164(bad), null);
assert.equal(providerHasVerifiedNumber(verified(n1), n1), true);
assert.equal(providerHasVerifiedNumber(verified(n2), n1), false);
assert.equal(providerHasVerifiedNumber({ data: { record_type: "verified_number", phone_number: n1 } }, n1), false);
assert.equal(providerHasVerifiedNumber({ data: { record_type: "not_verified", phone_number: n1, verified_at: "2026-09-29T12:00:00Z" } }, n1), false);
let lookups = 0;
const lookup = async n => { lookups++; return verified(n); };
const row = { user_id: "alice", phone_number: n1, status: "verified" };
assert.equal(await requireOwnerVerifiedCaller({ ownerId: "alice", numberRecord: row, providerLookup: lookup }), n1);
assert.equal(await requireOwnerVerifiedCaller({ ownerId: "bob", numberRecord: row, providerLookup: lookup }), null);
assert.equal(await requireOwnerVerifiedCaller({ ownerId: "alice", numberRecord: { ...row, status: "pending" }, providerLookup: lookup }), null);
assert.equal(lookups, 1, "Never query provider for another user's or unverified number");
assert.equal(await requireOwnerVerifiedCaller({ ownerId: "alice", numberRecord: row, providerLookup: async () => verified(n2) }), null);
assert.equal(await requireOwnerVerifiedCaller({ ownerId: "alice", numberRecord: row, providerLookup: async () => ({ data: {} }) }), null);
const requests = [];
const api = createTelnyxVerifiedNumbers({ apiKey: "fake-test-key", fetchImpl: async (url, options) => {
  requests.push({url,method:options.method,body:options.body && JSON.parse(options.body)});
  const number = n1;
  return {ok:true,status:200,json:async()=>options.method==="POST"&&options.body?.includes("verification_method")?
    {phone_number:number,verification_method:"sms"}:verified(number)};
}});
assert.equal(requests.length,0,"Do not send chargeable verification request implicitly");
await api.start(n1,"sms");
await api.submit(n1,"123456");
assert.equal(providerHasVerifiedNumber(await api.lookup(n1),n1),true);
assert.equal(requests[0].method,"POST");
assert.equal(requests[0].body.phone_number,n1);
assert.equal(requests[0].body.verification_method,"sms");
assert.equal(requests[1].body.verification_code,"123456");
assert.equal(requests[2].method,"GET");
assert.ok(requests[2].url.includes("verified_numbers/%2B4512345678"));
assert.throws(()=>api.start("not a number"),/Invalid/);
assert.throws(()=>api.submit(n1,"one"),/Invalid/);

const server=read("server.js"), html=read("index.html"), beta=read("public/phone-beta.html"), account=read("public/account.html");
const translatedRoute=server.split('app.post("/api/call",')[1]?.split('app.post("/api/hangup",')[0];
assert.ok(translatedRoute,"Translated call route exists");
assert.match(translatedRoute,/callerAccounts\.resolveCaller\(req\)/);
assert.match(translatedRoute,/from: caller\.number/);
assert.doesNotMatch(translatedRoute,/from: TELNYX_FROM_NUMBER/);
assert.doesNotMatch(translatedRoute,/from: req\.body/);
assert.match(translatedRoute,/if \(!callerAccounts\.enabled\) return res\.status\(503\)/,"Accounts fail closed");
assert.match(html,/\/api\/account\/me/);
assert.match(beta,/verified-user-number/);
assert.match(account,/verificationConsent/);
console.log("Per-user caller ID, provider state, anti-spoofing, UI and no-global-fallback checks passed.");
